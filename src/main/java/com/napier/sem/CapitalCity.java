package com.napier.sem;

/**
 * Represents a capital city for the Capital City Report.
 * Holds the columns required by the report: Name, Country and Population.
 */
public class CapitalCity {

    /** Name of the capital city. */
    public String name;

    /** Name of the country the city is the capital of. */
    public String country;

    /** Population of the capital city. */
    public int population;
}
